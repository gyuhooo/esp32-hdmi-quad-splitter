# ---------------------------------------------------------------- 電源
def buck(sh, ref_u, part, x, y, vout, en_net, fb_div, cin_small=True, en_rc=None, desc=""):
    """AP6320x 降圧: (U, CBST, L, CIN x2, COUT x2, EN 抵抗[+C], FB 分圧) を (x, y) を中心に置く。fb_div = (Rtop, Rbot) または None (固定電圧版)"""
    u = sh.symbol("Regulator_Switching:" + part, ref_u, part, (x, y), None, part + "-7", desc)
    px, py, _, _, _ = u["3"]; sh.wire(px, py, px - 10.16, py); sh.power("+5V", px - 10.16, py); sh.junction(px - 10.16, py)
    px, py, _, _, _ = u["2"]; sh.wire(px, py, px - 5.08, py); sh.label(en_net, px - 5.08, py, 180)
    px, py, _, _, _ = u["4"]; sh.power("GND", px, py, down=True)
    px, py, _, _, _ = u["5"]; sh.wire(px, py, px + 7.62, py); sh.label(f"{ref_u}_SW", px + 7.62, py, 0)
    px, py, _, _, _ = u["6"]; sh.wire(px, py, px + 7.62, py); sh.label(f"{ref_u}_BST", px + 7.62, py, 0)
    px, py, _, _, _ = u["1"]
    if fb_div:
        sh.wire(px, py, px - 5.08, py); sh.label(f"{ref_u}_FB", px - 5.08, py, 180)
        res(sh, fb_div[0], x - 30, y + 20, vout, f"{ref_u}_FB", f"{fb_div[0]} 1% 0402 (FB top)", role=f"{ref_u}_rtop")
        res(sh, fb_div[1], x - 30, y + 35, f"{ref_u}_FB", "GND", f"{fb_div[1]} 1% 0402 (FB bottom)", role=f"{ref_u}_rbot")
    else:
        sh.wire(px, py, px - 5.08, py); sh.label(vout, px - 5.08, py, 180)      # 固定電圧版: FB = VOUT
    cap(sh, "0.1uF", x + 40, y + 30, f"{ref_u}_BST", f"{ref_u}_SW", role=f"{ref_u}_cbst")
    lref = {"U3": "L1", "U4": "L2", "U5": "L3"}[ref_u]
    sh.two_pin("Device:L", lref, "4.7uH", x + 60, y + 30, f"{ref_u}_SW", vout, "Inductor_SMD:L_Taiyo-Yuden_NR-40xx", "NR4018T4R7M", "4.7uH 2.2A shielded inductor 4x4 mm")
    cap(sh, "10uF", x - 30, y + 70, "+5V", "GND", role=f"{ref_u}_cin1"); cap(sh, "10uF", x - 15, y + 70, "+5V", "GND", role=f"{ref_u}_cin2")
    if cin_small: cap(sh, "0.1uF", x, y + 70, "+5V", "GND", role=f"{ref_u}_cin0")
    cap(sh, "22uF", x + 30, y + 70, vout, "GND", role=f"{ref_u}_cout1"); cap(sh, "22uF", x + 45, y + 70, vout, "GND", role=f"{ref_u}_cout2")
    res(sh, "100k", x - 30, y - 30, "+5V", en_net, "100k 0402 (EN pull-up)", role=f"{ref_u}_ren")
    if en_rc:
        cap(sh, en_rc, x - 15, y - 30, en_net, "GND", desc=f"{en_rc} 0603 (EN delay)", role=f"{ref_u}_cen")
    sh.flag(vout, x + 60, y + 55)
    return u

def power_sheet(sheet_uuid, page):
    sh = Sheet("power.kicad_sch", "Power: USB-C 5 V in, 1.0 V / 1.8 V / 3.3 V bucks", sheet_uuid, page)
    sh.text("USB-C 5 V (2 A) -> PTC fuse -> +5V. Three synchronous bucks (AP63200 adj. / AP63203 3.3 V fixed, 2 A): +1V0 (VCCINT/VCCBRAM), +1V8 (VCCAUX), +3V3 (VCCO, I/O).", 20, 20, 2.0)
    sh.text("Power-on order per UG483 (VCCINT -> VCCAUX -> VCCO): U3 EN direct, U4 EN delayed ~30 ms (100k + 1uF), U5 EN delayed ~60 ms (100k + 2.2uF).", 20, 26, 1.5)
    j = sh.symbol("Connector:USB_C_Receptacle_USB2.0_16P", "J10", "USB-C 5V in", (60, 100),
                  "Connector_USB:USB_C_Receptacle_GCT_USB4105-xx-A_16P_TopMnt_Horizontal", "USB4105-GF-A", "USB-C receptacle 16P (power only)")
    x, y, _, _, _ = j["A4"]; sh.wire(x, y, x + 10.16, y); sh.label("VBUS", x + 10.16, y, 0)
    for num in ("A1", "S1"):
        x, y, _, _, _ = j[num]; sh.power("GND", x, y, down=True)
    for num in ("A6", "A7", "B6", "B7", "A8", "B8"):
        x, y, _, _, _ = j[num]; sh.nc(x, y)
    x, y, _, _, _ = j["A5"]; sh.wire(x, y, x + 7.62, y); sh.label("CC1", x + 7.62, y, 0)
    x, y, _, _, _ = j["B5"]; sh.wire(x, y, x + 7.62, y); sh.label("CC2", x + 7.62, y, 0)
    res(sh, "5.1k", 110, 130, "CC1", "GND", "5.1k 0402 (USB-C sink CC)", role="r_cc1")
    res(sh, "5.1k", 125, 130, "CC2", "GND", "5.1k 0402 (USB-C sink CC)", role="r_cc2")
    sh.two_pin("Device:Polyfuse", "F1", "2A", 110, 70, "VBUS", "+5V", "Fuse:Fuse_1206_3216Metric", "1206L200/12SLYR", "PTC resettable fuse 2 A hold, 1206")
    sh.flag("VBUS", 130, 90); sh.flag("+5V", 145, 90)
    cap(sh, "22uF", 160, 110, "+5V", "GND", role="c_5v")
    buck(sh, "U3", "AP63200WU", 230, 70, "+1V0", "U3_EN", ("10k", "40.2k"), desc="1.0 V 2 A synchronous buck (adj., FB 0.8 V), TSOT-23-6")
    buck(sh, "U4", "AP63200WU", 230, 180, "+1V8", "U4_EN", ("24.9k", "20k"), en_rc="1uF", desc="1.8 V 2 A synchronous buck (adj., FB 0.8 V), TSOT-23-6")
    buck(sh, "U5", "AP63203WU", 340, 180, "+3V3", "U5_EN", None, en_rc="2.2uF", desc="3.3 V 2 A synchronous buck (fixed), TSOT-23-6")
    sh.text("Vout = 0.8 V x (1 + Rtop/Rbot): U3 10k/40.2k = 1.00 V, U4 24.9k/20k = 1.80 V. L 4.7uH, CIN 2x10uF, COUT 2x22uF (+ FPGA bulk caps on fpga_cfg sheet).", 160, 262, 1.5)
    # 電源 LED
    d = sh.symbol("Device:LED", "D1", "PWR", (60, 200), "LED_SMD:LED_0603_1608Metric", LED_G, "Green LED 0603 (3.3 V power)")
    sh.label_pin(d, "2", "PWR_LED"); sh.label_pin(d, "1", "GND")
    res(sh, "1k", 60, 170, "+3V3", "PWR_LED", "1k 0402 (power LED)", role="r_pwr_led")
    # GND フラグ
    sh.pwr_flag(100, 200); sh.wire(100, 200, 100, 205); sh.power("GND", 100, 205, down=True)
    # 取付穴: H1-H4 はキャリア基板と同じ位置 (スペーサ 11 mm)、H5-H7 はこの基板だけ
    for i in range(7):
        sh.symbol("Mechanical:MountingHole", f"H{i + 1}", "M3", (30 + 15 * i, 240), "MountingHole:MountingHole_3.2mm_M3", "", "Mounting hole M3")
    sh.text("H1-H4 match the carrier board holes (M3 standoffs, 11 mm between the boards). H5-H7: main board only.", 20, 255, 1.5)
    sh.write()
    return sh

