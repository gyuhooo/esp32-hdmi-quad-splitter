_cnt = {"R": 0, "C": 0}
ROLES = {}          # role -> ref (gen_fpga_pcb.py が配置に使う)
def nref(k, role=None):
    _cnt[k] += 1
    ref = f"{k}{_cnt[k]}"
    if role:
        assert role not in ROLES, role
        ROLES[role] = ref
    return ref

def cap(sh, val, x, y, top, bottom, pkg=None, mpn=None, desc=None, role=None):
    fp, m, d = {"0.1uF": (C0402, MPN_C100N, "0.1uF 16V X7R 0402"), "0.47uF": (C0402, MPN_C470N, "0.47uF 10V X5R 0402"),
                "1uF": (C0603, MPN_C1U0603, "1uF 10V X5R 0603"), "2.2uF": (C0603, MPN_C2U2, "2.2uF 10V X5R 0603"),
                "4.7uF": (C0603, MPN_C4U7, "4.7uF 6.3V X5R 0603"), "10uF": (C0805, "GRM21BR61A106KE19L", "10uF 10V X5R 0805"),
                "22uF": (C0805, MPN_C22U, "22uF 6.3V X5R 0805"), "47uF": (C0805, MPN_C47U, "47uF 6.3V X5R 0805"),
                "100uF": (C1206, MPN_C100U, "100uF 6.3V X5R 1206")}[val]
    ref = nref("C", role)
    sh.two_pin("Device:C", ref, val, x, y, top, bottom, pkg or fp, mpn or m, desc or d)
    return ref

def res(sh, val, x, y, top, bottom, desc="", role=None):
    mpn = {"4.7k": "RC0402FR-074K7L", "10k": "RC0402FR-0710KL", "1k": "RC0402FR-071KL", "330R": "RC0402FR-07330RL", "100k": "RC0402FR-07100KL",
           "5.1k": "RC0402FR-075K1L", "40.2k": "RC0402FR-0740K2L", "20k": "RC0402FR-0720KL", "24.9k": "RC0402FR-0724K9L", "0R": "RC0402FR-070RL"}[val]
    ref = nref("R", role)
    sh.two_pin("Device:R", ref, val, x, y, top, bottom, R0402, mpn, desc or f"{val} 0402")
    return ref

def fpga_pins(sh, ppos, skip=()):
    """FPGA ユニットの各ピンにネット (fpga_common.NET_OF) を付ける"""
    for num, (x, y, ang, nm, typ) in ppos.items():
        if num in skip: continue
        net = F.NET_OF[num]
        if net == "NC":
            sh.nc(x, y)
        elif net in PLANE:
            sh.net_or_power(ppos, num, net)
        else:
            sh.label_pin(ppos, num, net)

