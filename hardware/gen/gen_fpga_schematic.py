def write_bom_and_pinmap():
    with open(os.path.join(OUT, "bom.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Reference", "Value", "Footprint", "MPN", "Description"])
        for ref in sorted(BOM, key=lambda r: (''.join(c for c in r if c.isalpha()), int(''.join(c for c in r if c.isdigit()) or 0))):
            b = BOM[ref]; w.writerow([ref, b["value"], b["footprint"], b["mpn"], b["desc"]])
    agg = {}
    for b in BOM.values():
        k = (b["value"], b["footprint"], b["mpn"], b["desc"])
        agg.setdefault(k, []).append(b["ref"])
    with open(os.path.join(OUT, "bom_grouped.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Qty", "Value", "Footprint", "MPN", "Description", "References"])
        for k, refs in sorted(agg.items(), key=lambda kv: -len(kv[1])):
            w.writerow([len(refs), k[0], k[1], k[2], k[3], " ".join(sorted(refs))])
    # ピン表: 全ボール
    hdr = {s: (h, p) for h, p, s, x, y in F.HEADER_ALL if s not in ("GND", "FPGA_5V")}
    with open(os.path.join(OUT, "fpga_pinmap.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Ball", "PinName", "Bank", "Net", "Header", "HeaderPin", "Direction(FPGA)", "Escape"])
        for pin in sorted(F.BALLS, key=lambda p: (F.ROWS.index(p[0]), int(p[1:]))):
            b = F.BALLS[pin]; net = F.NET_OF[pin]
            h, hp = hdr.get(net, ("", ""))
            d = ""
            if net.startswith("CH"): d = "in" if net.endswith(("HPD", "INT")) else "out"
            elif net.startswith("I2C"): d = "inout"
            elif net in ("CLK100", "RST_N") or net.startswith("SW"): d = "in"
            elif net.startswith("LED"): d = "out"
            elif net.startswith("PMOD"): d = "inout"
            e = F.PLAN.get(pin)
            esc = "" if not e else ("via" if e["kind"] != "signal" else f"{e['layer']} {e['dir']}")
            if b["ring"] <= 2 and b["kind"] == "IO": esc = "F.Cu"
            w.writerow([pin, b["name"], b["bank"] if b["bank"] is not None else "", net, h, hp, d, esc])

