#!/usr/bin/env python3
"""Vivado 用 XDC を生成する。

使い方: gen_xdc.py [hardware/fpga_main/fpga_pinmap.csv] > constraints/board.xdc

入力は FPGA メイン基板のピン表 (gen_fpga_schematic.py が出力、列: Ball, Net, ...)。
古い形式 (キャリア基板の fpga_header_pinmap.csv、列: Signal, FPGA_pin(fill in)) も読める。
hdl/top.v のポート名に合わせる: clk100, rst_n, hdmi_clk[3:0], hdmi_d[95:0], hdmi_de/hs/vs/hpd/int[3:0], i2c_scl/sda[1:0], led[3:0]。
"""
import csv, sys, re, os

path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "fpga_main", "fpga_pinmap.csv")
rows = list(csv.DictReader(open(path)))
pins = {}                       # net -> ball
for r in rows:
    if "Ball" in r:
        net, ball = r["Net"], r["Ball"]
    else:
        net, ball = r["Signal"], r["FPGA_pin(fill in)"].strip()
    if ball and net not in ("GND", "FPGA_5V", "NC"):
        pins[net] = ball

ports = {}                      # port -> (ball, extra attributes)
spare = {}
for net, ball in pins.items():
    m = re.fullmatch(r"CH([1-4])_(D(\d+)|CLK|DE|HS|VS|HPD|INT)", net)
    if m:
        ch = int(m.group(1)) - 1; kind = m.group(2)
        if m.group(3) is not None:
            ports[f"hdmi_d[{ch * 24 + int(m.group(3))}]"] = (ball, " SLEW FAST")
        elif kind in ("HPD", "INT"):
            ports[f"hdmi_{kind.lower()}[{ch}]"] = (ball, "")
        else:
            ports[f"hdmi_{kind.lower()}[{ch}]"] = (ball, " SLEW FAST")
        continue
    m = re.fullmatch(r"I2C_([AB])_(SCL|SDA)", net)
    if m:
        ports[f"i2c_{m.group(2).lower()}[{0 if m.group(1) == 'A' else 1}]"] = (ball, ""); continue
    m = re.fullmatch(r"LED(\d)", net)
    if m:
        ports[f"led[{m.group(1)}]"] = (ball, ""); continue
    if net == "CLK100": ports["clk100"] = (ball, "")
    elif net == "RST_N": ports["rst_n"] = (ball, " PULLUP true")
    elif re.fullmatch(r"(SW\d|PMOD_\d+)", net): spare[net] = ball

def key(p):
    m = re.match(r"(\w+)(?:\[(\d+)\])?", p); return (m.group(1), int(m.group(2) or 0))

print("## Generated by hardware/gen/gen_xdc.py from", os.path.basename(path))
print("## Board: FPGA main board (XC7A35T-1FTG256C) + quad HDMI TX carrier (J1/J2). All I/O 3.3 V LVCMOS.")
print("set_property CFGBVS VCCO [current_design]")
print("set_property CONFIG_VOLTAGE 3.3 [current_design]")
print("set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]")
print("set_property BITSTREAM.CONFIG.CONFIGRATE 33 [current_design]")
print("set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]")
print()
print("## 100 MHz oscillator (X1 -> MRCC) and reset button")
for port in ("clk100", "rst_n"):
    if port in ports:
        ball, extra = ports[port]
        print(f"set_property -dict {{PACKAGE_PIN {ball} IOSTANDARD LVCMOS33{extra}}} [get_ports {{{port}}}]")
print("create_clock -period 10.000 -name clk100 [get_ports clk100]")
print()
print("## ADV7513 parallel RGB (carrier J1/J2), I2C, LEDs")
for port in sorted((p for p in ports if p not in ("clk100", "rst_n")), key=key):
    ball, extra = ports[port]
    print(f"set_property -dict {{PACKAGE_PIN {ball} IOSTANDARD LVCMOS33{extra}}} [get_ports {{{port}}}]")
print()
print("## Spare I/O on the main board (not used by hdl/top.v - uncomment and add the ports to use them). SW0-3: DIP switch to GND, enable PULLUP.")
for net, ball in sorted(spare.items(), key=lambda kv: (kv[0][:2], int(re.search(r"\d+", kv[0]).group()))):
    extra = " PULLUP true" if net.startswith("SW") else ""
    print(f"# set_property -dict {{PACKAGE_PIN {ball} IOSTANDARD LVCMOS33{extra}}} [get_ports {{{net.lower()}}}]")
print()
print("## The four pixel clocks are asynchronous to each other and to clk100")
print("set_clock_groups -asynchronous \\")
for i in range(4):
    print(f"  -group [get_clocks -of_objects [get_pins ch{i}/u_clk/u_mmcm/CLKOUT0]] \\")
print("  -group [get_clocks clk100]")
missing = [n for n in ("CLK100", "RST_N") if n not in pins]
if missing:
    print(f"## WARNING: missing nets {missing}", file=sys.stderr)
